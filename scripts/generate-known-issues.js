#!/usr/bin/env node
/**
 * Generate Known Issues page from TODO/FIXME comments in codebase
 * 
 * Usage: node scripts/generate-known-issues.js > KNOWN_ISSUES.md
 * 
 * This script greps the codebase for TODO, FIXME, HACK, and XXX comments
 * and generates a markdown page listing all known issues.
 * 
 * Honest enforcement: this makes TODOs visible to users rather than
 * hidden in code comments.
 */

const { execSync } = require('child_process');
const fs = require('fs');
const path = require('path');

const PATTERNS = ['TODO', 'FIXME', 'HACK', 'XXX'];
const EXCLUDE_DIRS = ['node_modules', '.git', 'dist', 'build'];
const INCLUDE_EXTS = ['.js', '.ts', '.jsx', '.tsx', '.html', '.css'];

function grepPattern(pattern) {
  try {
    const excludeArgs = EXCLUDE_DIRS.map(d => `--exclude-dir=${d}`).join(' ');
    const includeArgs = INCLUDE_EXTS.map(e => `--include=${e}`).join(' ');
    const cmd = `grep -rn "${pattern}" . ${excludeArgs} ${includeArgs} 2>/dev/null || true`;
    const output = execSync(cmd, { encoding: 'utf8', cwd: path.join(__dirname, '..') });
    return output.trim().split('\n').filter(line => line);
  } catch (e) {
    return [];
  }
}

function parseLine(line) {
  const match = line.match(/^([^:]+):(\d+):(.*)$/);
  if (!match) return null;
  const [, file, lineNum, content] = match;
  const pattern = PATTERNS.find(p => content.includes(p));
  if (!pattern) return null;
  
  // Extract the actual comment content after the pattern
  const patternIndex = content.indexOf(pattern);
  const comment = content.slice(patternIndex + pattern.length).trim().replace(/^[:\s-]+/, '');
  
  return {
    file: file.replace(/^\.\//, ''),
    line: lineNum,
    pattern,
    comment: comment || '(no description)',
  };
}

function generateMarkdown(issues) {
  if (issues.length === 0) {
    return `# Known Issues

No TODO/FIXME comments found in the codebase.

This page is generated automatically by \`scripts/generate-known-issues.js\`.
`;
  }

  const grouped = issues.reduce((acc, issue) => {
    if (!acc[issue.pattern]) acc[issue.pattern] = [];
    acc[issue.pattern].push(issue);
    return acc;
  }, {});

  let md = `# Known Issues

This page is automatically generated from TODO/FIXME/HACK/XXX comments in the codebase.
Last updated: ${new Date().toISOString()}

Generated by: \`scripts/generate-known-issues.js\`

---

`;

  for (const pattern of PATTERNS) {
    const items = grouped[pattern];
    if (!items || items.length === 0) continue;

    md += `## ${pattern} (${items.length})

`;
    for (const item of items) {
      md += `- **\`${item.file}:${item.line}\`**: ${item.comment}\n`;
    }
    md += '\n';
  }

  return md;
}

function main() {
  const allIssues = [];
  
  for (const pattern of PATTERNS) {
    const lines = grepPattern(pattern);
    for (const line of lines) {
      const parsed = parseLine(line);
      if (parsed) allIssues.push(parsed);
    }
  }

  // Sort by file, then line number
  allIssues.sort((a, b) => {
    if (a.file !== b.file) return a.file.localeCompare(b.file);
    return parseInt(a.line) - parseInt(b.line);
  });

  const markdown = generateMarkdown(allIssues);
  console.log(markdown);
}

main();
